export function guideBySlug(slug: string) {
  return guides.find((guide) => guide.slug === slug) ?? null;
}

export function guideForWorld(world: string) {
  return guides.find((guide) => guide.world === world) ?? null;
}

export function lessonThumb(href: string) {
  try {
    const url = new URL(href);
    if (!url.hostname.includes("youtu")) return null;
    const id = url.searchParams.get("v") || url.pathname.split("/").filter(Boolean).pop() || "";
    return /^[A-Za-z0-9_-]{6,}$/.test(id) ? `https://i.ytimg.com/vi/${id}/hqdefault.jpg` : null;
  } catch {
    return null;
  }
}
